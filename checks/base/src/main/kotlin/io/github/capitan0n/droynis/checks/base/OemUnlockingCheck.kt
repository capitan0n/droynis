package io.github.capitan0n.droynis.checks.base

import io.github.capitan0n.droynis.core.Category
import io.github.capitan0n.droynis.core.Check
import io.github.capitan0n.droynis.core.CheckSpec
import io.github.capitan0n.droynis.core.Evidence
import io.github.capitan0n.droynis.core.Outcome
import io.github.capitan0n.droynis.core.Reading
import io.github.capitan0n.droynis.core.Remediation
import io.github.capitan0n.droynis.core.ScanContext
import io.github.capitan0n.droynis.core.SettingsActions
import io.github.capitan0n.droynis.core.Severity
import io.github.capitan0n.droynis.core.evaluate
import kotlin.time.Duration.Companion.seconds

/**
 * The OEM unlocking switch, as the system mirrors it in a property. With the bootloader already
 * unlocked the switch decides nothing, and the property is one a root module can fake, so the check
 * then doesn't apply instead of passing on a "0": INTG-1040 reports the bootloader.
 */
class OemUnlockingCheck(
    private val properties: SystemProperties,
    private val attestation: AttestationProbe,
) : Check {

    override val spec = CheckSpec(
        id = "INTG-1041",
        category = Category.DEVICE_INTEGRITY,
        title = "OEM unlocking",
        severity = Severity.NOTICE,
        explanation = "While OEM unlocking is allowed, the bootloader can be unlocked from a computer in " +
            "minutes. Unlocking wipes your data, but it also defeats Factory Reset Protection, so a stolen " +
            "phone can be reset and resold, and it is the first step to installing a modified system.",
        remediation = Remediation(
            text = "Turn off OEM unlocking in Developer options. The switch is greyed out while the bootloader " +
                "is unlocked or when the carrier does not allow unlocking. If Developer options are off, turn them on " +
                "first: in About phone, tap Build number seven times.",
            settingsActions = listOf(SettingsActions.DEVELOPER_OPTIONS),
            highlightKey = "oem_unlock_enable",
        ),
        // Shares the attested key with INTG-1040, which can take a few seconds to make it.
        timeout = 20.seconds,
        failsWhen = "the OEM unlocking switch is on (not applicable once the bootloader is unlocked)",
    )

    override suspend fun run(context: ScanContext): Outcome {
        val props = properties.all()
        val values = (props as? Reading.Value)?.value.orEmpty()
        val evidence = if (props is Reading.Value) {
            listOf(OEM_UNLOCK_ALLOWED, OEM_UNLOCK_SUPPORTED).map { Evidence(it, values[it] ?: "(not readable)", props.source) }
        } else {
            emptyList()
        }
        unlockedBootloader(values)?.let { proof ->
            return Outcome.unsupported(
                "The bootloader is already unlocked (INTG-1040), so this switch no longer protects anything",
                evidence + proof,
            )
        }
        return props.evaluate("System properties", evidence) {
            when {
                values[OEM_UNLOCK_ALLOWED] == "1" -> Outcome.fail("OEM unlocking is allowed", evidence)
                values[OEM_UNLOCK_ALLOWED] == "0" -> Outcome.pass("OEM unlocking is off", evidence)
                values[OEM_UNLOCK_SUPPORTED] == "0" -> Outcome.pass("This phone does not allow bootloader unlocking", evidence)
                else -> Outcome.unknown("This phone does not let apps read the OEM unlocking switch", evidence)
            }
        }
    }

    /**
     * Evidence that the bootloader is unlocked: the hardware-attested state, else a boot property
     * saying so. Null when neither says it; a property saying "locked" proves nothing either way.
     */
    private fun unlockedBootloader(values: Map<String, String>): Evidence? {
        val attested = attestation.attest()
        // A software-only attestation is generated by the OS being judged, so it proves nothing.
        val root = (attested as? Reading.Value)?.value?.takeIf { it.securityLevel != SecurityLevel.SOFTWARE }?.rootOfTrust
        if (root != null) {
            return Evidence("Device locked (attested)", "false", attested.source).takeIf { !root.deviceLocked }
        }
        val props = properties.all()
        return when {
            values[BootloaderCheck.FLASH_LOCKED] == "0" -> Evidence(BootloaderCheck.FLASH_LOCKED, "0", props.source)
            values[BootloaderCheck.DEVICE_STATE] == "unlocked" -> Evidence(BootloaderCheck.DEVICE_STATE, "unlocked", props.source)
            else -> null
        }
    }

    companion object {
        /** Mirrors the OEM unlocking switch; set by the system from the persistent data block. */
        const val OEM_UNLOCK_ALLOWED = "sys.oem_unlock_allowed"
        const val OEM_UNLOCK_SUPPORTED = "ro.oem_unlock_supported"
    }
}
