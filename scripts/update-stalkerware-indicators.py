#!/usr/bin/env python3
"""Regenerate the stalkerware indicator list that SUSP-5007 checks installed apps against.

Reads ioc.yaml and watchware.yaml from a checkout of
https://github.com/AssoEchap/stalkerware-indicators (CC BY 4.0) and writes
checks/base/src/main/kotlin/io/github/capitan0n/droynis/checks/base/StalkerwareIndicatorData.kt.
Only app names, package names and signing-certificate SHA-1 fingerprints are kept: Droynis can't
see network traffic, so domains and IPs are useless to it.

    git clone --depth 1 https://github.com/AssoEchap/stalkerware-indicators /tmp/sw
    python3 scripts/update-stalkerware-indicators.py /tmp/sw

Needs PyYAML (Arch/Manjaro: python-yaml, Debian/Ubuntu: python3-yaml).
"""

import re
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "checks/base/src/main/kotlin/io/github/capitan0n/droynis/checks/base/StalkerwareIndicatorData.kt"
SOURCES = [("ioc.yaml", "STALKERWARE"), ("watchware.yaml", "WATCHWARE")]

PACKAGE = re.compile(r"^[A-Za-z][A-Za-z0-9_]*(\.[A-Za-z0-9_]+)+$")
SHA1 = re.compile(r"^[0-9A-F]{40}$")


def kotlin_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def kotlin_list(values: list[str], indent: str) -> str:
    """One value per line, so an update's diff shows each indicator added or removed."""
    if not values:
        return "emptyList()"
    return "listOf(\n" + "".join(f"{indent}    {kotlin_string(v)},\n" for v in values) + f"{indent})"


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, text=True).stdout.strip()


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(f"usage: {sys.argv[0]} <checkout of AssoEchap/stalkerware-indicators>")
    repo = Path(sys.argv[1])
    commit, date = git(repo, "log", "-1", "--format=%H %cs").split()

    families = []
    seen_packages: dict[str, str] = {}
    seen_certificates: dict[str, str] = {}
    for file_name, kind in SOURCES:
        for entry in yaml.safe_load((repo / file_name).read_text(encoding="utf-8")) or []:
            name = str(entry["name"]).strip()
            packages, certificates = [], []
            for package in entry.get("packages") or []:
                package = str(package).strip()
                if not PACKAGE.match(package):
                    print(f"skipped package {package!r} of {name}: not a package name", file=sys.stderr)
                elif package in seen_packages:
                    print(f"skipped package {package} of {name}: already listed for {seen_packages[package]}", file=sys.stderr)
                else:
                    seen_packages[package] = name
                    packages.append(package)
            for certificate in entry.get("certificates") or []:
                certificate = str(certificate).strip().replace(":", "").upper()
                if not SHA1.match(certificate):
                    print(f"skipped certificate {certificate!r} of {name}: not a SHA-1 fingerprint", file=sys.stderr)
                elif certificate in seen_certificates:
                    print(f"skipped certificate {certificate} of {name}: already listed for {seen_certificates[certificate]}", file=sys.stderr)
                else:
                    seen_certificates[certificate] = name
                    certificates.append(certificate)
            if packages or certificates:
                families.append((name, kind, sorted(packages), sorted(certificates)))

    lines = [
        "// Generated by scripts/update-stalkerware-indicators.py: do not edit by hand.",
        "//",
        "// The data in this file is \"Stalkerware Indicators\" by Echap,",
        "// https://github.com/AssoEchap/stalkerware-indicators, licensed under CC BY 4.0",
        "// (https://creativecommons.org/licenses/by/4.0/). Changes: only app names, package names and",
        "// signing-certificate SHA-1 fingerprints from ioc.yaml and watchware.yaml are kept, reformatted",
        "// as Kotlin. Echap gives no guarantee that the indicators are accurate.",
        "",
        "package io.github.capitan0n.droynis.checks.base",
        "",
        "import io.github.capitan0n.droynis.checks.base.IndicatorKind.STALKERWARE",
        "import io.github.capitan0n.droynis.checks.base.IndicatorKind.WATCHWARE",
        "",
        "internal object StalkerwareIndicatorData {",
        f"    const val COMMIT = {kotlin_string(commit)}",
        f"    const val DATE = {kotlin_string(date)}",
        "",
        "    val FAMILIES: List<IndicatorFamily> = listOf(",
    ]
    for name, kind, packages, certificates in families:
        lines.append("        IndicatorFamily(")
        lines.append(f"            {kotlin_string(name)},")
        lines.append(f"            {kind},")
        lines.append(f"            packages = {kotlin_list(packages, '            ')},")
        lines.append(f"            certificates = {kotlin_list(certificates, '            ')},")
        lines.append("        ),")
    lines += ["    )", "}", ""]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")

    stalkerware = sum(1 for f in families if f[1] == "STALKERWARE")
    print(
        f"{OUTPUT.relative_to(ROOT)}: {stalkerware} stalkerware and {len(families) - stalkerware} watchware apps, "
        f"{len(seen_packages)} packages, {len(seen_certificates)} certificates (commit {commit[:12]}, {date})",
    )


if __name__ == "__main__":
    main()
